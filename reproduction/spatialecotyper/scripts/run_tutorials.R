sha256_file <- function(path) {
  output <- system2("sha256sum", shQuote(path), stdout = TRUE, stderr = TRUE)
  status <- attr(output, "status")
  if (!is.null(status) && status != 0L) {
    stop(paste(output, collapse = "\n"))
  }
  sub("[[:space:]].*$", "", output[[1]])
}

verify_source <- function() {
  observed <- system2(
    "git", c("-C", shQuote(official_repo), "rev-parse", "HEAD"),
    stdout = TRUE
  )
  stopifnot(identical(observed, official_commit))
}

verify_archive <- function() {
  output <- system2(
    "sha256sum", c("--check", shQuote(checksum_path)),
    stdout = TRUE, stderr = TRUE
  )
  status <- attr(output, "status")
  if (!is.null(status) && status != 0L) {
    stop(paste(output, collapse = "\n"))
  }
  invisible(output)
}

prepare_runtime_rmd <- function(tutorial_id, rmd_name) {
  original <- file.path(official_repo, "vignettes", rmd_name)
  work_dir <- file.path(work_root, tutorial_id)
  result_dir <- file.path(result_root, tutorial_id)
  dir.create(work_dir, recursive = TRUE, showWarnings = FALSE)
  dir.create(result_dir, recursive = TRUE, showWarnings = FALSE)

  runtime <- file.path(work_dir, rmd_name)
  text <- readLines(original, warn = FALSE)
  manifest <- read.delim(manifest_path, stringsAsFactors = FALSE, check.names = FALSE)
  stopifnot(nrow(manifest) == 21L)
  input_adapter <- "official_urls_to_sha256_verified_local_archive"
  strict_material_status <- "PASS"
  strict_material_issue <- ""
  adapted_input_sha256 <- ""
  for (i in seq_len(nrow(manifest))) {
    local_path <- file.path(raw_dir, manifest$file[[i]])
    stopifnot(file.exists(local_path), file.info(local_path)$size > 0)
    if (tutorial_id == "T02" &&
        manifest$file[[i]] == "Melanoma1_subset_SpatialEcoTyper_results.rds") {
      archived_result <- readRDS(local_path)
      archived_fields <- colnames(archived_result$obj@meta.data)
      if (!all(c("Spot.X", "Spot.Y") %in% archived_fields)) {
        upstream_path <- file.path(
          work_root, "T01", "Melanoma1_subset_SpatialEcoTyper_results.rds"
        )
        stopifnot(file.exists(upstream_path), file.info(upstream_path)$size > 0)
        local_path <- upstream_path
        input_adapter <- paste0(
          input_adapter,
          ";T02_uses_T01_official_output"
        )
        strict_material_status <- "FAIL_INPUT_SCHEMA_WITH_OFFICIAL_UPSTREAM_FALLBACK"
        strict_material_issue <- paste0(
          "Archived melanoma RDS lacks Spot.X/Spot.Y required by fixed ",
          "AnnotateCells; substituted output generated by official T01"
        )
        adapted_input_sha256 <- sha256_file(upstream_path)
      }
    }
    text <- gsub(manifest$url[[i]], local_path, text, fixed = TRUE)
  }
  writeLines(text, runtime, useBytes = TRUE)

  images_source <- file.path(official_repo, "vignettes", "images")
  images_target <- file.path(work_dir, "images")
  if (dir.exists(images_source) && !dir.exists(images_target)) {
    copied <- file.copy(images_source, work_dir, recursive = TRUE)
    stopifnot(isTRUE(copied), dir.exists(images_target))
  }

  list(
    original = original,
    runtime = runtime,
    work_dir = work_dir,
    result_dir = result_dir,
    input_adapter = input_adapter,
    strict_material_status = strict_material_status,
    strict_material_issue = strict_material_issue,
    adapted_input_sha256 = adapted_input_sha256,
    output_html = file.path(
      result_dir,
      paste0(tools::file_path_sans_ext(rmd_name), ".html")
    )
  )
}

render_one <- function(tutorial_id) {
  order <- read.delim(order_path, stringsAsFactors = FALSE)
  row <- order[order$tutorial_id == tutorial_id, , drop = FALSE]
  stopifnot(nrow(row) == 1L)
  paths <- prepare_runtime_rmd(tutorial_id, row$rmd[[1]])
  options(width = 120)
  render_env <- new.env(parent = globalenv())
  render_env$download.file <- function(url, destfile, ...) {
    if (length(url) == 1L && file.exists(url)) {
      copied <- file.copy(url, destfile, overwrite = TRUE)
      if (!isTRUE(copied)) stop(sprintf("Failed to stage archived input: %s", url))
      return(invisible(0L))
    }
    utils::download.file(url, destfile, ...)
  }
  rmarkdown::render(
    input = paths$runtime,
    output_format = "html_document",
    output_file = basename(paths$output_html),
    output_dir = paths$result_dir,
    intermediates_dir = paths$work_dir,
    knit_root_dir = paths$work_dir,
    clean = FALSE,
    envir = render_env,
    quiet = FALSE
  )
  stopifnot(file.exists(paths$output_html), file.info(paths$output_html)$size > 0)
}

