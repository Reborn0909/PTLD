write_records <- function(records) {
  records <- records[base::order(records$order), , drop = FALSE]
  temp <- paste0(status_path, ".part")
  write.table(records, temp, sep = "\t", row.names = FALSE, quote = FALSE, na = "")
  stopifnot(file.rename(temp, status_path))
  invisible(records)
}

